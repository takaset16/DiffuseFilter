def _class_names(name, data_root, data_dir):
    if name == "CUB":
        with open(os.path.join(_cub_root(data_root), "classes.txt")) as f:
            return sorted(line.strip().split(" ", 1)[1] for line in f if line.strip())
    if name == "StanfordCars":
        return torchvision.datasets.StanfordCars(root=data_root, split="train").classes
    if name == "FGVCAircraft":
        return torchvision.datasets.FGVCAircraft(root=data_root, split="trainval", annotation_level="variant").classes
    # Flowers102 folders are numbered 000-101, 0-101 or 1-102 depending on the generator version.
    names = set(os.listdir(data_dir))
    if "000" in names:
        return [f"{i:03d}" for i in range(102)]
    if "0" in names:
        return [str(i) for i in range(102)]
    if "102" in names:
        return [str(i + 1) for i in range(102)]
    return [f"{i:03d}" for i in range(102)]


class DiffuseMixDataset(Dataset):
    """Images generated by DiffuseMix.

    max_k keeps only files "<image>_blended_<prompt>_<k>.jpg" with k <= max_k
    (0: one image per prompt; -1: all images).
    """
    EXTS = {".jpg", ".jpeg", ".png", ".bmp", ".webp"}

    def __init__(self, name, diffusemix_dir, data_root, transform=None, max_k=-1):
        self.transform = transform
        self.max_k = None if max_k is None or int(max_k) < 0 else int(max_k)
        self.data_dir = os.path.join(diffusemix_dir, f"{name}_augmented")
        if not os.path.isdir(self.data_dir):
            raise FileNotFoundError(f"DiffuseMix directory not found: {self.data_dir}")
        class_names = _class_names(name, data_root, self.data_dir)
        self.samples = self._build_samples(class_names)
        print(f"[DiffuseMixDataset] {name}: {len(self.samples)} images from {self.data_dir}")

    def _keep(self, fname):
        if os.path.splitext(fname)[1].lower() not in self.EXTS:
            return False
        if self.max_k is None:
            return True
        m = re.search(r"_(\d+)\.[A-Za-z]+$", fname)
        return m is None or int(m.group(1)) <= self.max_k

    def _build_samples(self, class_names):
        samples, missing = [], []
        for label, cls in enumerate(class_names):
            found = False
            # Class names containing "/" are stored either as nested folders or with "_".
            for c in dict.fromkeys([cls, cls.replace("/", "_")]):
                d = os.path.join(self.data_dir, c)
                if not os.path.isdir(d):
                    continue
                files = [f for f in sorted(os.listdir(d)) if self._keep(f) and os.path.isfile(os.path.join(d, f))]
                if files:
                    samples.extend((os.path.join(d, f), label) for f in files)
                    found = True
            if not found:
                missing.append(cls)
        if missing:
            print(f"[DiffuseMixDataset] warning: no images for {len(missing)} classes, e.g. {missing[:5]}")
        return samples

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, index):
        path, label = self.samples[index]
        img = Image.open(path).convert("RGB")
        if self.transform is not None:
            img = self.transform(img)
        return img, label


# ---------------------------------------------------------------------------
# Validation split for hyperparameter selection (the test set is not used)
# ---------------------------------------------------------------------------

def _stratified_split(labels, val_ratio, seed=0):
    by_cls = defaultdict(list)
    for i, y in enumerate(labels):
        by_cls[int(y)].append(i)
    rng = random.Random(seed)
    tr, va = [], []
    for c in sorted(by_cls):
        idx = by_cls[c][:]
        rng.shuffle(idx)
        n_val = max(1, int(round(len(idx) * val_ratio)))
        va.extend(idx[:n_val])
        tr.extend(idx[n_val:])
    return sorted(tr), sorted(va)


def build_train_val(name, data_root, val_ratio=0.1, split_seed=0):
    """Aircraft and Flowers use the official val split; CUB and Cars hold out a stratified val_ratio."""
    if name in ("FGVCAircraft", "Flowers102"):
        cls = torchvision.datasets.FGVCAircraft if name == "FGVCAircraft" else torchvision.datasets.Flowers102
        kw = {"annotation_level": "variant"} if name == "FGVCAircraft" else {}
        return (cls(root=data_root, split="train", transform=TRAIN_TRANSFORM, **kw),
                cls(root=data_root, split="val", transform=TEST_TRANSFORM, **kw))
    d_tr = _official(name, data_root, "train", TRAIN_TRANSFORM)
    d_ev = _official(name, data_root, "train", TEST_TRANSFORM)
    if name == "CUB":
        labels = (d_tr.data["target"].values - 1).tolist()
    else:
        labels = [lbl for _, lbl in d_tr._samples]
    tr, va = _stratified_split(labels, val_ratio, split_seed)
    return Subset(d_tr, tr), Subset(d_ev, va)


def build_datasets(name, data_root, diffusemix=None, diffusemix_dir="", dm_max_k=-1,
                   val_mode="none", val_ratio=0.1):
    """diffusemix: None (original images), "only" (generated images) or "combine" (both)."""
    if val_mode == "holdout":
        if diffusemix:
            raise ValueError("val_mode=holdout cannot be combined with DiffuseMix data")
        return build_train_val(name, data_root, val_ratio)

    test = _official(name, data_root, "test", TEST_TRANSFORM)
    if not diffusemix:
        return _official(name, data_root, "train", TRAIN_TRANSFORM), test
    generated = DiffuseMixDataset(name, diffusemix_dir, data_root, TRAIN_TRANSFORM, max_k=dm_max_k)
    if diffusemix == "combine":
        return ConcatDataset([_official(name, data_root, "train", TRAIN_TRANSFORM), generated]), test
    return generated, test
