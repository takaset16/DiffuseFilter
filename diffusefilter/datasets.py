import os
import random
import re
from collections import defaultdict

import pandas as pd
import torchvision
from PIL import Image
from torch.utils.data import ConcatDataset, Dataset, Subset
from torchvision import transforms

from .augment import IMAGENET_MEAN, IMAGENET_STD

DATASETS = ("CUB", "StanfordCars", "FGVCAircraft", "Flowers102")
NUM_CLASSES = {"CUB": 200, "StanfordCars": 196, "FGVCAircraft": 100, "Flowers102": 102}

TRAIN_TRANSFORM = transforms.Compose([
    transforms.Resize((256, 256)),
    transforms.RandomCrop(224),
    transforms.RandomHorizontalFlip(),
    transforms.ToTensor(),
    transforms.Normalize(IMAGENET_MEAN, IMAGENET_STD),
])
TEST_TRANSFORM = transforms.Compose([
    transforms.Resize((224, 224)),
    transforms.ToTensor(),
    transforms.Normalize(IMAGENET_MEAN, IMAGENET_STD),
])


class CUBDataset(Dataset):
    def __init__(self, root, train=True, transform=None):
        self.root = root
        self.transform = transform
        read = lambda f, cols: pd.read_csv(os.path.join(root, f), sep=" ", header=None, names=cols)
        data = (read("images.txt", ["img_id", "filepath"])
                .merge(read("image_class_labels.txt", ["img_id", "target"]), on="img_id")
                .merge(read("train_test_split.txt", ["img_id", "is_train"]), on="img_id"))
        self.data = data[data["is_train"] == int(train)]

    def __len__(self):
        return len(self.data)

    def __getitem__(self, idx):
        row = self.data.iloc[idx]
        image = Image.open(os.path.join(self.root, "images", row["filepath"])).convert("RGB")
        if self.transform:
            image = self.transform(image)
        return image, row["target"] - 1


def _cub_root(data_root):
    return os.path.join(data_root, "CUB_200_2011")


def _official(name, data_root, split, transform):
    if name == "CUB":
        return CUBDataset(_cub_root(data_root), train=(split == "train"), transform=transform)
    if name == "StanfordCars":
        return torchvision.datasets.StanfordCars(root=data_root, split=split, transform=transform)
    if name == "FGVCAircraft":
        split = "trainval" if split == "train" else split
        return torchvision.datasets.FGVCAircraft(root=data_root, split=split, annotation_level="variant",
                                                 transform=transform)
    if name == "Flowers102":
        return torchvision.datasets.Flowers102(root=data_root, split=split, transform=transform)
    raise ValueError(f"unknown dataset: {name}")


